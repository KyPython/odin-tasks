'use strict';
const assert=require('node:assert/strict'), fs=require('node:fs'), path=require('node:path');
const run=name=>new Function('input',fs.readFileSync(path.join(__dirname,'../cloud/'+name+'-evidence.js'),'utf8'));
const manifest=run('manifest'), pr=run('pr');
const file=(name,body)=>({path:name,content_b64:Buffer.from(body).toString('base64')});
const comments=files=>[{id:1,body:'ODIN_STARTER_MANIFEST\n'+JSON.stringify({files})}];
assert.equal(manifest({comments:comments([file('src/main.py','print(1)\n')])}).file_count,1);
assert.throws(()=>manifest({comments:comments([file('src/main.py','x'.repeat(50001))])}),/cap/);
assert.throws(()=>manifest({comments:comments([file('../main.py','x')])}),/path/);
assert.throws(()=>manifest({comments:comments([file('src'+String.fromCharCode(92)+'main.py','x')])}),/path/);
assert.throws(()=>manifest({comments:comments([file('src/a','x'),file('src/a','y')])}),/duplicate/);
assert.throws(()=>manifest({comments:comments([{path:'src/a',content_b64:'/w=='}])}),/Binary/);
assert.throws(()=>manifest({comments:Array(100).fill({body:''})}),/Incomplete/);
const input={pr:{merged:true,merged_at:'2026-10-07',head:{sha:'a'.repeat(40)},changed_files:1},files:[{filename:'src/a.py',status:'added',patch:'+print(1)'}]};
assert.equal(pr(input).head_sha,'a'.repeat(40));
assert.throws(()=>pr({...input,pr:{...input.pr,merged:false}}),/Merged/);
assert.throws(()=>pr({...input,files:[]}),/Incomplete/);
assert.throws(()=>pr({...input,files:[{filename:'src/a.py'}]}),/Missing/);
assert.throws(()=>pr({...input,files:[{filename:'src/a.py',patch:'x'.repeat(42001)}]}),/cap/);
process.stdout.write('12 complete-source-review checks passed\n');
